--
--   business_directors.is_director  respuesta a "¿Es director o miembro del
--        directorio?" del representante legal. Hasta ahora el backend enviaba
--        is_director=true fijo a Bridge (dato posiblemente falso para un
--        apoderado). business_ubos.is_director ya existía.
--   documents.document_subtype  tipo del comprobante de domicilio
--        (utility_bill / bank_statement / lease_agreement), las tres opciones
--        de "Select address proof" de Tazapay.
--   businesses.tazapay_vertical*  vertical de Tazapay propuesto con la tabla
--        NAICS → vertical y confirmado por el staff antes de enviar.
--   businesses.ownership_in_incorporation_doc  el cliente indica que el
--        testimonio de constitución (incorporation_certificate) ya muestra a los
--        socios y sus porcentajes vigentes: ese archivo se envía también como
--        estructura accionaria (Bridge ownership_information / Tazapay
--        shareholder_registry) sin subir otro.
--   businesses.shareholding_same_as_registration  casilla "Same as Business
--        Registration" de Tazapay. Solo la marca el staff (en unipersonales el
--        backend la calcula al enviar).
--   tazapay_industry_verticals / naics_tazapay_vertical_map  catálogo de los
--        295 verticales y equivalencias NAICS → vertical (gana el prefijo más
--        largo). Generado con Docuemntacion_nueva_integracion/scripts_tabla_naics.
--        Política: solo verticales que describen honestamente la actividad; sin
--        vertical o no elegible → la empresa queda solo con Bridge.

ALTER TABLE public.business_directors
  ADD COLUMN IF NOT EXISTS is_director boolean;

ALTER TABLE public.documents
  ADD COLUMN IF NOT EXISTS document_subtype text
  CHECK (document_subtype IS NULL OR document_subtype IN ('utility_bill', 'bank_statement', 'lease_agreement'));

CREATE TABLE IF NOT EXISTS public.tazapay_industry_verticals (
  vertical   text PRIMARY KEY,
  vgroup     text NOT NULL,
  high_risk  boolean NOT NULL DEFAULT false,
  is_active  boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.naics_tazapay_vertical_map (
  naics_prefix        text PRIMARY KEY CHECK (naics_prefix ~ '^[0-9]{2,6}$'),
  vertical            text REFERENCES public.tazapay_industry_verticals(vertical),
  quality             text NOT NULL
                      CHECK (quality IN ('exacta', 'generica', 'confirmar_tazapay', 'sin_vertical', 'no_elegible')),
  requires_compliance boolean NOT NULL DEFAULT false,
  note                text,
  CHECK ((quality IN ('sin_vertical', 'no_elegible')) = (vertical IS NULL))
);

ALTER TABLE public.businesses
  ADD COLUMN IF NOT EXISTS tazapay_vertical text REFERENCES public.tazapay_industry_verticals(vertical),
  ADD COLUMN IF NOT EXISTS tazapay_vertical_quality text,
  ADD COLUMN IF NOT EXISTS tazapay_vertical_confirmed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS tazapay_vertical_confirmed_at timestamptz,
  ADD COLUMN IF NOT EXISTS shareholding_same_as_registration boolean,
  ADD COLUMN IF NOT EXISTS ownership_in_incorporation_doc boolean;

