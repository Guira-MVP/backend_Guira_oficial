REVOKE ALL ON TABLE public.naics_tazapay_vertical_map FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.tazapay_industry_verticals TO service_role;
GRANT ALL ON TABLE public.naics_tazapay_vertical_map TO service_role;

